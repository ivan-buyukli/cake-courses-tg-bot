export const catalogs: Record<Locale, Catalog> = { en, ua };
export type TextKey = keyof Catalog;
export const t = (locale: Locale, key: TextKey): string =>
  catalogs[detectLocale(locale)][key];
export function detectLocale(value?: string): Locale {
  const base = value?.toLowerCase().split(/[-_]/)[0];
  if (base === "uk") return "ua";
  return locales.includes(base as Locale) ? (base as Locale) : "en";
}
